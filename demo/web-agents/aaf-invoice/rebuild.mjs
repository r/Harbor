// Rebuild the vendored browser module from an immutable AAF revision.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const revision = '12d68a3ed71051e01d1625c8d0cc08039cef838c';
const checkout = resolve(process.argv[2] || '../aaf');
const temporary = mkdtempSync(join(tmpdir(), 'harbor-aaf-'));
try {
  const archive = execFileSync('git', ['-C', checkout, 'archive', revision], { maxBuffer: 30 * 1024 * 1024 });
  execFileSync('tar', ['-x', '-C', temporary], { input: archive });
  execFileSync('npm', ['ci', '--ignore-scripts', '--no-audit', '--no-fund'], { cwd: temporary, stdio: 'inherit' });
  const entry = join(temporary, 'harbor-entry.ts');
  writeFileSync(entry, `
export { ChatUI } from './packages/aaf-agent-widget/src/ui/chat.ts';
export { WidgetPlanner } from './packages/aaf-agent-widget/src/widget-planner.ts';
export { enrichCatalogWithSchema } from './packages/aaf-agent-widget/src/navigation.ts';
export { SemanticParser, ManifestValidator } from './packages/agent-runtime-core/src/index.ts';
export { getInvoices, createInvoice } from './samples/billing-app/src/store.ts';
`);
  const aliases = {
    'runtime-core': 'agent-runtime-core',
    contracts: 'aaf-contracts',
    'planner-local': 'aaf-planner-local',
  };
  execFileSync(join(temporary, 'node_modules/.bin/esbuild'), [entry, '--bundle', '--format=esm',
    '--platform=browser', '--target=firefox115', '--minify', '--legal-comments=inline',
    ...Object.entries(aliases).map(([name, folder]) => `--alias:@agent-accessibility-framework/${name}=${join(temporary, 'packages', folder, 'src/index.ts')}`),
    `--banner:js=/* AAF ${revision}. Generated by rebuild.mjs. MIT, see LICENSE.aaf. */`,
    `--metafile=${join(temporary, 'bundle-meta.json')}`,
    `--outfile=${fileURLToPath(new URL('./aaf.bundle.js', import.meta.url))}`,
  ], { env: { ...process.env, NODE_PATH: join(temporary, 'node_modules') }, stdio: 'inherit' });
  const metadata = JSON.parse(readFileSync(join(temporary, 'bundle-meta.json'), 'utf8'));
  const packages = new Set();
  for (const input of Object.keys(metadata.inputs).filter(input => input.includes('node_modules/'))) {
    let directory = dirname(resolve(input));
    while (!existsSync(join(directory, 'package.json'))) directory = dirname(directory);
    packages.add(directory);
  }
  const licenses = [...packages].sort().map(directory => {
    const info = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
    const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license'].find(name => existsSync(join(directory, name)));
    if (!license) throw new Error(`Missing license for ${info.name}`);
    return `${info.name} ${info.version}\n\n${readFileSync(join(directory, license), 'utf8')}`;
  });
  writeFileSync(fileURLToPath(new URL('./THIRD_PARTY_LICENSES.txt', import.meta.url)), licenses.join('\n\n'));
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
